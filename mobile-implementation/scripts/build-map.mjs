// Bundles map/main.ts + Leaflet (+ the prebuilt MapLibre GL file) into one HTML string for the WebView.
// Outputs (gitignored, regenerated on `npm install` / `npm start`):
//   src/map/mapHtml.generated.ts   MAP_HTML (boot data is injected at runtime by MapView)
//   .local/map-preview.html        open in a desktop browser to check the map against a local API
//                                  server on port 8787 (dev panel)
import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...parts) => join(root, ...parts);
const read = (file) => readFileSync(file, 'utf8');
const fill = (text, token, content) => {
  if (!text.includes(token)) throw new Error(`placeholder ${token} not found`);
  return text.replace(token, () => content);
};

// MapLibre GL (vector basemap) ships as one prebuilt UMD file that is inlined as its own <script>;
// the Leaflet bridge's require('maplibre-gl') resolves to that global instead of re-bundling it.
const maplibreGlobal = {
  name: 'maplibre-global',
  setup(b) {
    b.onResolve({ filter: /^maplibre-gl$/ }, () => ({ path: 'maplibre-gl', namespace: 'maplibre-global' }));
    b.onLoad({ filter: /.*/, namespace: 'maplibre-global' }, () => ({ contents: 'module.exports = window.maplibregl;' }));
  },
};

const { outputFiles } = await build({
  entryPoints: [p('map/main.ts')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: ['es2019'],
  write: false,
  logLevel: 'warning',
  plugins: [maplibreGlobal],
});
const js = outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const maplibreJs = read(p('node_modules/maplibre-gl/dist/maplibre-gl.js')).replace(/<\/script/gi, '<\\/script');

let html = read(p('map/template.html'));
html = fill(html, '/*__LEAFLET_CSS__*/', read(p('node_modules/leaflet/dist/leaflet.css')));
html = fill(html, '/*__MAPLIBRE_CSS__*/', read(p('node_modules/maplibre-gl/dist/maplibre-gl.css')));
html = fill(html, '/*__APP_CSS__*/', read(p('map/style.css')));
html = fill(html, '/*__MAPLIBRE_JS__*/', maplibreJs);
html = fill(html, '/*__APP_JS__*/', js);

const header = '// Generated by scripts/build-map.mjs — do not edit.\n';
mkdirSync(p('src/map'), { recursive: true });
writeFileSync(
  p('src/map/mapHtml.generated.ts'),
  `${header}export const MAP_HTML: string = ${JSON.stringify(fill(html, '<!--__DEV__-->', ''))};\n`,
);

const DEV_PANEL = `
<div style="position:fixed;top:8px;left:8px;z-index:1000;background:#fff;padding:8px;border-radius:8px;
  font:12px system-ui;box-shadow:0 1px 4px #0005;max-width:300px">
  <b>Map preview (dev only, API on localhost:8787)</b><br>
  <button onclick="__app.cmd({mode:'routes'})">Bus Routes</button>
  <button onclick="__app.cmd({mode:'crowding'})">Crowding</button>
  <button onclick="__app.cmd({focus:null})">Clear selection</button>
  <pre id="log" style="max-height:90px;overflow:auto;margin:4px 0 0;white-space:pre-wrap"></pre>
</div>
<script>
const API = 'http://localhost:8787';
fetch(API + '/api/stops').then(r => r.json()).then(p => __app.cmd({ stops: p.stops.map(s => [s[0], s[2], s[3]]) }));
const poll = () => fetch(API + '/api/live').then(r => r.json())
  .then(p => __app.cmd({ liveData: { now: p.now, rows: p.vehicles } })).finally(() => setTimeout(poll, 25000));
poll();
addEventListener('mapmsg', async (e) => {
  const log = document.getElementById('log');
  log.textContent = JSON.stringify(e.detail) + '\\n' + log.textContent;
  if (e.detail.type !== 'tap' || e.detail.kind !== 'stop') return;
  const info = await (await fetch(API + '/api/stops/' + e.detail.stopId)).json();
  const ids = info.routes.map(r => r.id);
  const { routes } = await (await fetch(API + '/api/routes?ids=' + ids.join(','))).json();
  const h = String(new Date().getHours());
  __app.cmd({ focus: { busRoutes: ids, busKeys: [], pinStop: e.detail.stopId, highlight: null, fit: false,
    routes: Object.values(routes).map((d, i) => ({ id: d.route.id, number: d.route.number, direction: d.route.direction,
      color: ['#1a73e8', '#8e24aa', '#0b8043', '#e37400'][i % 4], shape: d.route.shape, stops: d.route.stops,
      occ: (d.crowding[h] || {}).occ || [], confidence: (d.crowding[h] || {}).confidence || 'none' })) } });
});
</script>`;

const meta = JSON.parse(read(p('assets/data/meta.json')));
const boot = JSON.stringify({ levels: meta.assumptions.levels, state: { mode: 'routes' } });
mkdirSync(p('.local'), { recursive: true });
writeFileSync(
  p('.local/map-preview.html'),
  fill(fill(html, '/*__BOOT_JSON__*/null', boot.replace(/</g, '\\u003c')), '<!--__DEV__-->', DEV_PANEL),
);

console.log(`map bundle: ${(html.length / 1024).toFixed(0)} KB html`);
